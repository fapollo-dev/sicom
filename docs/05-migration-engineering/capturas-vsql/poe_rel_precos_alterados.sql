      --AND COALESCE(I.PROMOCAO,'N') = CAST(PROMO AS VARCHAR2(1))
        GROUP BY ROWNUM, E.CODEMPRESA,  E.FANTASIA,  P.CODDPTO, F.DESCRICAO, P.DESCRICAO,  P.IDPRODUTO,
        M.IDPRODUTO, M.CODEMPRESA, M.OBS, M.VRVENDA, I.VRVENDA , I.VRCUSTO, I.VRCUSTOREP , I.VRPROMO, I.PROMOCAO, I.IDEMPRESA, OPE.LOGIN
        ORDER BY E.CODEMPRESA,   E.FANTASIA,  P.CODDPTO, F.DESCRICAO, P.DESCRICAO, M.OBS
      ) GROUP BY CODIGO, CODEMPRESA, FANTASIA, DPTO, IDPRODUTO, DESCRICAO, VALORLOTE,VENDAATUAL,PROMOCAO,VRPROMO,DTINI,DTFIM,VRVENDASUG,CUSTOATUAL,ULTCUSTO,USUARIO,VENDAANT,ESTOQ,ULTDTVENDA;
