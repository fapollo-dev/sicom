        SELECT ROWNUM CODIGO,  E.CODEMPRESA, E.FANTASIA, F.DESCRICAO DPTO,M.IDPRODUTO,  P.DESCRICAO,
        COALESCE(M.VRVENDA, 0) VALORLOTE, COALESCE(I.VRVENDA, 0) VENDAATUAL, COALESCE(I.PROMOCAO, 'N') PROMOCAO ,COALESCE(I.VRPROMO, 0) VRPROMO,
        (SELECT TRUNC(A.DTINICIOPROMOCAO) FROM AGENDA_PROMOCAO_ITENS I
         LEFT JOIN AGENDA_PROMOCAO A ON A.CODAGENDA = I.CODAGENDA
         WHERE I.IDPRODUTO = M.IDPRODUTO AND A.FLAGPROMOCAO = 'E' AND I.IDEMPRESA = M.CODEMPRESA AND ROWNUM = 1  ) DTINI,
        (SELECT TRUNC(A.DTFIMPROMOCAO) FROM AGENDA_PROMOCAO_ITENS I
         LEFT JOIN AGENDA_PROMOCAO A ON A.CODAGENDA = I.CODAGENDA
         WHERE I.IDPRODUTO = M.IDPRODUTO AND A.FLAGPROMOCAO = 'E' AND I.IDEMPRESA = M.CODEMPRESA AND ROWNUM = 1 ) DTFIM,
        MAX(NP.VRVENDASUG) VRVENDASUG,
         COALESCE(I.VRCUSTOREP, COALESCE(I.VRCUSTO, 0)) CUSTOATUAL,
         MAX(NP.ULTCUSTO) ULTCUSTO,
         CASE  SUBSTR(M.OBS,1, 23) WHEN 'REFERENTE A NOTA FISCAL'
         THEN
           MAX(NF.USULTALTERACAO)||'-'||OPE.LOGIN
         ELSE
          TRIM(SUBSTR(M.OBS,68, 40)) END USUARIO,
        MAX(NP.ULTVENDA)  VENDAANT,
        COALESCE(MAX(ES.QTDE),0) ESTOQ,
        MAX(NF.DTCONTABIL) ULTDTVENDA
        FROM LOTEPRECO M
        LEFT JOIN PRODUTOS P ON (M.IDPRODUTO = P.IDPRODUTO)
        LEFT JOIN MULTI_PRECO I ON I.IDPRODUTO = M.IDPRODUTO AND I.IDEMPRESA = M.CODEMPRESA
        LEFT JOIN FAMILIAS_PROD F ON (F.CODFAMILIA = P.CODDPTO)
        LEFT JOIN EMPRESAS E ON (M.CODEMPRESA = E.CODEMPRESA)
        LEFT JOIN ESTOQUE ES ON(P.IDPRODUTO = ES.IDPRODUTO AND M.CODEMPRESA = ES.IDEMPRESA)
        LEFT JOIN AUX_PRECO_ALTERADO A ON A.CODLOTEPRECO = M.CODLOTEPRECO
        LEFT JOIN NF ON NF.NRONF = A.NRONF AND ((TRUNC(NF.DTULTIMALTERACAO) = TRUNC(M.DATALOTE)) OR (TRUNC(NF.DTCONTABIL) = TRUNC(M.DATALOTE))) AND ROWNUM = 1
        LEFT JOIN NF_PROD NP ON NP.CODNF = NF.CODNF AND NP.CODPRODUTO = M.IDPRODUTO
        LEFT JOIN OPERADORES OPE ON OPE.CODOPERADOR = NF.USULTALTERACAO
        WHERE TRUNC(M.DATALOTE) BETWEEN CAST(DT_INI AS VARCHAR(10)) AND CAST(DT_FIM AS VARCHAR2(10))
